'''
Clean and standardize the disease data in .json files generated by get_disease_data.py.

Double-check that the symptoms listed have relevant evidence. 

'''

import json
import re
import requests
from pathlib import Path
from typing import Any, Dict, List, Optional


OLLAMA_URL = "http://localhost:11434/api/chat"


# -----------------------------
# Basic cleaning helpers
# -----------------------------

def clean_text(value: Any) -> str:
    if value is None:
        return ""
    text = str(value)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def normalize_label(text: str) -> str:
    """
    Normalize symptom/test labels for deduplication.
    Example: 'Generalized body convulsions' -> 'generalized body convulsions'
    """
    text = clean_text(text).lower()
    text = text.replace("–", "-").replace("—", "-")
    text = re.sub(r"[^\w\s\-()/>]", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def dedupe_by_name(items: List[Dict[str, Any]], name_key: str) -> List[Dict[str, Any]]:
    """
    Deduplicate list of dicts by normalized name.
    Keeps first instance, but appends later evidence sentences when useful.
    """
    seen = {}

    for item in items:
        name = clean_text(item.get(name_key, ""))
        if not name:
            continue

        norm = normalize_label(name)

        if norm not in seen:
            seen[norm] = item
        else:
            old_evidence = clean_text(seen[norm].get("evidence_sentence", ""))
            new_evidence = clean_text(item.get("evidence_sentence", ""))

            if new_evidence and new_evidence not in old_evidence:
                combined = old_evidence
                if combined:
                    combined += " | "
                combined += new_evidence
                seen[norm]["evidence_sentence"] = combined

            old_temp = clean_text(seen[norm].get("temporality", ""))
            new_temp = clean_text(item.get("temporality", ""))

            if new_temp and new_temp not in old_temp:
                combined_temp = old_temp
                if combined_temp:
                    combined_temp += " | "
                combined_temp += new_temp
                seen[norm]["temporality"] = combined_temp

    return list(seen.values())


def is_bad_or_empty_entry(value: str) -> bool:
    value = clean_text(value).lower()
    return value in {"", "none", "n/a", "unknown", "not reported"}


# -----------------------------
# Field-specific cleanup
# -----------------------------

def clean_symptoms(symptoms_raw: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    cleaned = []

    for s in symptoms_raw:
        raw_symptom = clean_text(s.get("raw_symptom", ""))

        if is_bad_or_empty_entry(raw_symptom):
            continue

        cleaned.append({
            "name": normalize_label(raw_symptom),
            "display_name": raw_symptom,
            "status": clean_text(s.get("status", "present")) or "present",
            "temporality": clean_text(s.get("temporality", "")),
            "evidence_sentence": clean_text(s.get("evidence_sentence", ""))
        })

    return dedupe_by_name(cleaned, "name")


def clean_negative_findings(negative_raw: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    cleaned = []

    for n in negative_raw:
        finding = clean_text(n.get("finding", ""))
        status = clean_text(n.get("status", ""))

        if is_bad_or_empty_entry(finding):
            continue

        # Avoid resolved/improved symptoms being treated as truly absent.
        # These can be useful, but should not go into symptoms_absent.
        if status.lower() in {"resolved", "improved"}:
            continue

        cleaned.append({
            "name": normalize_label(finding),
            "display_name": finding,
            "status": status or "absent",
            "evidence_sentence": clean_text(n.get("evidence_sentence", ""))
        })

    return dedupe_by_name(cleaned, "name")


def clean_tests(tests_raw: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    cleaned = []

    for t in tests_raw:
        test = clean_text(t.get("test", ""))
        result = clean_text(t.get("result", ""))
        evidence = clean_text(t.get("evidence_sentence", ""))

        if is_bad_or_empty_entry(test):
            continue

        # Skip test entries with no result and no useful evidence
        if not result and not evidence:
            continue

        cleaned.append({
            "test": test,
            "result": result,
            "evidence_sentence": evidence
        })

    return dedupe_by_name(cleaned, "test")


def clean_mimics(mimics_raw: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    cleaned = []

    for m in mimics_raw:
        diagnosis = clean_text(m.get("diagnosis", ""))
        evidence = clean_text(m.get("evidence_sentence", ""))

        if is_bad_or_empty_entry(diagnosis):
            continue

        # Do not include the true diagnosis as a mimic.
        if "acute intermittent porphyria" in diagnosis.lower():
            continue

        cleaned.append({
            "diagnosis": diagnosis,
            "evidence_sentence": evidence
        })

    return dedupe_by_name(cleaned, "diagnosis")


# -----------------------------
# Optional Ollama review
# -----------------------------

def call_ollama_json(
    prompt: str,
    model: str = "llama3.1:8b",
    temperature: float = 0.0
) -> Optional[Dict[str, Any]]:
    payload = {
        "model": model,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are a clinical data-cleaning assistant. "
                    "Return only valid JSON. Do not include markdown."
                )
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        "stream": False,
        "options": {
            "temperature": temperature
        }
    }

    try:
        response = requests.post(OLLAMA_URL, json=payload, timeout=120)
        response.raise_for_status()
        content = response.json()["message"]["content"]
        return json.loads(content)
    except Exception as e:
        print(f"Ollama review failed: {e}")
        return None


def classify_symptom_evidence_with_ollama(
    diagnosis: str,
    symptoms_present: List[str],
    labs_or_tests: List[Dict[str, Any]],
    model: str = "llama3.1:8b"
) -> Dict[str, List[str]]:
    """
    Uses Ollama to classify features into:
    - red_flag_features
    - discriminating_features
    - nonspecific_features

    This is useful for later ambiguity generation.
    """

    prompt = f"""
Ground-truth diagnosis:
{diagnosis}

Symptoms present:
{json.dumps(symptoms_present, indent=2)}

Diagnostic tests/labs:
{json.dumps(labs_or_tests, indent=2)}

Task:
Classify the symptoms and test findings into the following categories:

1. red_flag_features:
Features that strongly support the diagnosis or are clinically important warning signs.

2. discriminating_features:
Features that help distinguish this diagnosis from common mimics.

3. nonspecific_features:
Features that are common and could fit many diseases.

Return JSON only in this exact format:
{{
  "red_flag_features": [],
  "discriminating_features": [],
  "nonspecific_features": [],
  "notes": ""
}}
"""

    result = call_ollama_json(prompt, model=model)

    if result is None:
        return {
            "red_flag_features": [],
            "discriminating_features": [],
            "nonspecific_features": symptoms_present,
            "notes": "Ollama classification failed; all symptoms defaulted to nonspecific."
        }

    return {
        "red_flag_features": result.get("red_flag_features", []),
        "discriminating_features": result.get("discriminating_features", []),
        "nonspecific_features": result.get("nonspecific_features", []),
        "notes": result.get("notes", "")
    }


# -----------------------------
# Vignette generation
# -----------------------------

def make_vignette(patient: Dict[str, Any]) -> str:
    age = clean_text(patient["patient_profile"].get("age", ""))
    sex = clean_text(patient["patient_profile"].get("sex", ""))

    symptoms = patient.get("symptoms_present", [])
    tests = patient.get("labs_or_tests", [])

    symptom_text = ", ".join(symptoms[:8])

    test_phrases = []
    for t in tests:
        test_name = clean_text(t.get("test", ""))
        result = clean_text(t.get("result", ""))
        evidence = clean_text(t.get("evidence_sentence", ""))

        if result:
            test_phrases.append(f"{test_name} showed {result}")
        elif evidence:
            test_phrases.append(evidence)

    test_text = " ".join(test_phrases[:3])

    opening = "A patient presents"
    if age and sex:
        opening = f"A {age}-year-old {sex} presents"
    elif age:
        opening = f"A {age}-year-old patient presents"
    elif sex:
        opening = f"A {sex} patient presents"

    vignette = f"{opening} with {symptom_text}."

    if test_text:
        vignette += f" Relevant diagnostic information includes: {test_text}"

    return vignette.strip()


# -----------------------------
# Main conversion function
# -----------------------------

def simplify_case_report_json(
    raw_data: Dict[str, Any],
    use_ollama: bool = True,
    ollama_model: str = "llama3.1:8b"
) -> List[Dict[str, Any]]:
    """
    Converts your extracted case-report JSON into simpler test-patient records.
    """

    simplified_patients = []

    query_info = raw_data.get("query", {})
    disease_query = clean_text(query_info.get("disease", ""))

    for record_index, record in enumerate(raw_data.get("records", [])):
        pmcid = clean_text(record.get("pmcid", ""))
        pubmed_url = clean_text(record.get("pubmed_url", ""))
        year = clean_text(record.get("year", ""))
        abstract = clean_text(record.get("abstract", ""))
        review_status = clean_text(record.get("review_status", ""))

        patients = (
            record
            .get("extraction", {})
            .get("patients", [])
        )

        for patient_index, patient_raw in enumerate(patients):
            patient_id = clean_text(patient_raw.get("patient_id", f"case_{patient_index + 1}"))

            diagnosis = clean_text(
                patient_raw.get("confirmed_diagnosis", "")
                or disease_query
            )

            symptoms_structured = clean_symptoms(
                patient_raw.get("symptoms_presented", [])
            )

            symptoms_present = [
                s["display_name"] for s in symptoms_structured
            ]

            symptoms_absent_structured = clean_negative_findings(
                patient_raw.get("negative_findings", [])
            )

            symptoms_absent = [
                n["display_name"] for n in symptoms_absent_structured
            ]

            labs_or_tests = clean_tests(
                patient_raw.get("diagnostic_tests", [])
            )

            candidate_mimics = clean_mimics(
                patient_raw.get("initial_misdiagnoses_or_mimics", [])
            )

            case_id_parts = []
            if pmcid:
                case_id_parts.append(pmcid)
            else:
                case_id_parts.append(f"record_{record_index + 1}")

            case_id_parts.append(patient_id)

            case_id = "_".join(case_id_parts)

            simplified = {
                "case_id": case_id,
                "source": {
                    "pmcid": pmcid,
                    "pubmed_url": pubmed_url,
                    "year": year,
                    "review_status": review_status
                },
                "ground_truth_diagnosis": diagnosis,
                # "disease_category": "rare",
                "patient_profile": {
                    "age": clean_text(patient_raw.get("age", "")),
                    "sex": clean_text(patient_raw.get("sex", ""))
                },
                # "presenting_complaint": infer_presenting_complaint(symptoms_present),
                "symptoms_present": symptoms_present,
                # "symptoms_present_structured": symptoms_structured,
                "symptoms_absent": symptoms_absent,
                # "symptoms_absent_structured": symptoms_absent_structured,
                "labs_or_tests": labs_or_tests,
                "candidate_mimics": candidate_mimics,
                "final_diagnosis_evidence": clean_text(
                    patient_raw.get("final_diagnosis_evidence", "")
                ),
                "red_flag_features": [],
                "discriminating_features": [],
                "nonspecific_features": [],
                "vignette": "",
                # "source_abstract": abstract
            }

            if use_ollama:
                evidence_classes = classify_symptom_evidence_with_ollama(
                    diagnosis=diagnosis,
                    symptoms_present=symptoms_present,
                    labs_or_tests=labs_or_tests,
                    model=ollama_model
                )

                simplified["red_flag_features"] = evidence_classes["red_flag_features"]
                simplified["discriminating_features"] = evidence_classes["discriminating_features"]
                simplified["nonspecific_features"] = evidence_classes["nonspecific_features"]
                simplified["ollama_review_notes"] = evidence_classes["notes"]
            else:
                simplified["nonspecific_features"] = symptoms_present
                simplified["ollama_review_notes"] = "Ollama review not used."

            simplified["vignette"] = make_vignette(simplified)

            simplified_patients.append(simplified)

    return simplified_patients


def infer_presenting_complaint(symptoms: List[str]) -> str:
    """
    Simple heuristic. You can replace this with an Ollama-generated
    presenting complaint later if desired.
    """
    if not symptoms:
        return ""

    priority_terms = [
        "abdominal pain",
        "seizures",
        "convulsions",
        "weakness",
        "vomiting",
        "tea-colored urine",
        "hyponatremia"
    ]

    selected = []

    for term in priority_terms:
        for symptom in symptoms:
            if term.lower() in symptom.lower() and symptom not in selected:
                selected.append(symptom)

    if not selected:
        selected = symptoms[:3]

    return ", ".join(selected[:4])


# -----------------------------
# File I/O wrapper
# -----------------------------

def clean_json_file(
    input_path: str,
    output_path: str,
    use_ollama: bool = True,
    ollama_model: str = "llama3.2:3b"
) -> List[Dict[str, Any]]:
    input_path = Path(input_path)
    output_path = Path(output_path)

    with input_path.open("r", encoding="utf-8") as f:
        raw_data = json.load(f)

    simplified = simplify_case_report_json(
        raw_data,
        use_ollama=use_ollama,
        ollama_model=ollama_model
    )

    with output_path.open("w", encoding="utf-8") as f:
        json.dump(simplified, f, indent=2, ensure_ascii=False)

    return simplified

def prompt_required(prompt_text: str) -> str:
    """
    Prompt until the user enters a non-empty value.
    """
    while True:
        value = input(prompt_text).strip()
        if value:
            return value
        print("This field is required.")


